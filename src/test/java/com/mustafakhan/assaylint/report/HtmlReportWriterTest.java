package com.mustafakhan.assaylint.report;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.mustafakhan.assaylint.model.Severity;
import java.io.IOException;
import java.util.List;
import org.junit.jupiter.api.Test;

class HtmlReportWriterTest {

    private static String render(Report report) throws IOException {
        StringBuilder out = new StringBuilder();
        new HtmlReportWriter().write(report, out);
        return out.toString();
    }

    @Test
    void isSelfContained() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.startsWith("<!DOCTYPE html>"));
        assertTrue(html.contains("<style>"));
        assertFalse(html.contains("<link"));
        assertFalse(html.contains("src="));
        assertFalse(html.contains("@import"));
        assertFalse(html.contains("url("));
        assertFalse(html.contains("http://"));
        assertFalse(html.contains("https://"));
    }

    @Test
    void showsWordmarkVersionAndFooter() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("<span class=\"wordmark\">assay-lint</span>"));
        assertTrue(html.contains("<span class=\"version\">v9.9.9</span>"));
        assertTrue(html.contains("Generated by assay-lint v9.9.9</span><span>2026-02-01 09:30:00 UTC</span>"));
    }

    @Test
    void failedBannerCountsErrorsAndWarnings() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("class=\"banner banner-failed\""));
        assertTrue(html.contains("Failed \u2014 2 errors, 2 warnings"));
    }

    @Test
    void warningsOnlyPassWithWarningsByDefault() throws IOException {
        String html = render(Reports.warningsOnly(Severity.ERROR));

        assertTrue(html.contains("class=\"banner banner-warning\""));
        assertTrue(html.contains(">Passed with warnings<"));
        assertTrue(html.contains("2 warnings, none at or above the fail-on level (error)."));
    }

    @Test
    void warningsFailWhenFailOnIsWarning() throws IOException {
        String html = render(Reports.warningsOnly(Severity.WARNING));

        assertTrue(html.contains("Failed \u2014 0 errors, 2 warnings"));
        assertTrue(html.contains("at or above the fail-on level (warning)"));
    }

    @Test
    void cleanReportPassesWithoutTable() throws IOException {
        String html = render(Reports.clean());

        assertTrue(html.contains("class=\"banner banner-passed\""));
        assertTrue(html.contains("No issues found."));
        assertFalse(html.contains("<table"));
        assertFalse(html.contains("Issues by rule"));
        assertFalse(html.contains("class=\"stat stat-error\""));
        assertFalse(html.contains("class=\"stat stat-warning\""));
    }

    @Test
    void runDetailsUseForwardSlashesAndShortHashWithFullTooltip() throws IOException {
        Report report = new Report(Reports.metadata("C:\\lab\\run 7\\samples.csv", Reports.FULL_HASH, Severity.ERROR),
                List.of());

        String html = render(report);

        assertTrue(html.contains("<dd>C:/lab/run 7/samples.csv</dd>"), html);
        assertTrue(html.contains("<code title=\"" + Reports.FULL_HASH + "\">9350be05f3b8\u2026</code>"), html);
        assertTrue(html.contains("<dd>2026-02-01 09:30:00 UTC</dd>"));
        String rows = html.substring(html.indexOf("<dt>Rows</dt>"));
        String rowsText = rows.substring(0, rows.indexOf("</dd>")).replaceAll("<[^>]+>", "");
        assertEquals("Rows3 read \u00B7 2 parsed \u00B7 1 with issues \u00B7 1 clean \u00B7 1 unparsed", rowsText);
    }

    @Test
    void overviewHasThreeStatCards() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("<span class=\"stat-label\">Total issues</span><span class=\"stat-value\">4</span>"));
        assertTrue(html.contains("<div class=\"stat stat-error\"><span class=\"stat-label\">Errors</span>"
                + "<span class=\"stat-value\">2</span>"));
        assertTrue(html.contains("<div class=\"stat stat-warning\"><span class=\"stat-label\">Warnings</span>"
                + "<span class=\"stat-value\">2</span>"));
        assertEquals(3, html.split("class=\"stat ", -1).length - 1);
    }

    @Test
    void issuesByRuleUsesReadableNames() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("<h2>Issues by rule</h2>"));
        assertTrue(html.contains("<li><span>Unknown assay</span>"));
        assertFalse(html.contains(">UnknownAssay<"));
    }

    @Test
    void issueTableHasSortableColumnsAndSeverityPills() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("data-type=\"num\" data-dir=\"asc\" aria-sort=\"ascending\">Line</th>"));
        assertTrue(html.contains(">Sample</th>") && html.contains(">Severity</th>") && html.contains(">Rule</th>")
                && html.contains(">Message</th>"));
        assertTrue(html.contains("<span class=\"pill pill-error\">Error</span>"));
        assertTrue(html.contains("<span class=\"pill pill-warning\">Warning</span>"));
        assertFalse(html.contains(">ERROR<"));
        assertTrue(html.contains("addEventListener('click'"));
        assertEquals(4, html.split("<tr><td", -1).length - 1);
    }

    @Test
    void fileLevelIssueShowsFileAndNoSample() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("<td class=\"num\" data-value=\"0\">File</td><td data-value=\"\">"
                + "<span class=\"none\" aria-label=\"none\">\u2014</span></td>"), html);
    }

    @Test
    void printStylesHideSortArrowsAndKeepColors() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("print-color-adjust:exact"));
        assertTrue(html.contains("@media print{"));
        assertTrue(html.contains("th[data-dir]::after{content:none}"));
    }

    @Test
    void escapesUserControlledText() throws IOException {
        String html = render(Reports.withIssues());

        assertTrue(html.contains("Assay &lt;x&gt; &amp; &quot;y&quot; is unknown"));
        assertFalse(html.contains("Assay <x>"));
    }

    @Test
    void escapeHandlesQuotes() {
        assertEquals("it&#39;s", HtmlReportWriter.escape("it's"));
    }
}
